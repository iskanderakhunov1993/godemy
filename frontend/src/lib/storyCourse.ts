export function getStoryCourseLesson(slug: string): Lesson | null {
  return storyCourseLessons.find((lessonItem) => lessonItem.slug === slug) || null
}

export function getStoryModuleMeta(moduleName: string): StoryModuleMeta | null {
  return storyModuleMeta.find((moduleItem) => moduleItem.name === moduleName) || null
}

export function getStoryLessonsByModule(moduleName: string): Lesson[] {
  return storyCourseLessons
    .filter((lessonItem) => lessonItem.module === moduleName)
    .sort((left, right) => left.order - right.order || left.id - right.id)
}

export function getStoryLessonsByTopic(topicName: string, moduleName?: string): Lesson[] {
  return storyCourseLessons
    .filter((lessonItem) => lessonItem.category === topicName)
    .filter((lessonItem) => !moduleName || lessonItem.module === moduleName)
    .sort((left, right) => left.order - right.order || left.id - right.id)
}
